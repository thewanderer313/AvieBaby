#!/usr/bin/env node
/**
 * Regenerate src/books/BookRegistry.ts by scanning assets/books/.
 *
 * Source of truth:
 *   - assets/books/<book-id>/book.json          (titles, reader display names)
 *   - assets/books/<book-id>/pages/page-NN.png  (page images, NN sets order)
 *   - assets/books/<book-id>/voices/<reader>/page-NN.mp3 (audio per page)
 *   - assets/books/<book-id>/cover.png          (optional thumbnail)
 *
 * Reader display names that aren't listed in book.json fall back to the reader id.
 * Books without book.json fall back to using their id as the title.
 *
 * Usage:
 *   node scripts/book-register.js
 *   (or simply: scripts/book-register.js — has a #! shebang)
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const ASSETS_DIR = path.join(ROOT, 'assets/books');
const OUTPUT = path.join(ROOT, 'src/books/BookRegistry.ts');

function listSubdirs(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();
}

function listFilesMatching(dir, pattern) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter((f) => pattern.test(f)).sort();
}

function readBookInfo(bookId) {
  const infoPath = path.join(ASSETS_DIR, bookId, 'book.json');
  if (!fs.existsSync(infoPath)) {
    console.warn(`WARN: ${path.relative(ROOT, infoPath)} missing; using id as title.`);
    return { title: bookId, readers: {} };
  }
  try {
    const info = JSON.parse(fs.readFileSync(infoPath, 'utf8'));
    if (!info.readers) info.readers = {};
    if (!info.title) info.title = bookId;
    return info;
  } catch (e) {
    console.warn(`WARN: failed to parse ${path.relative(ROOT, infoPath)}: ${e.message}; using id as title.`);
    return { title: bookId, readers: {} };
  }
}

function escapeSingleQuoted(s) {
  return String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

const books = listSubdirs(ASSETS_DIR);

let out = `import { Book } from './types';

// Generated by scripts/book-register.js — do not edit by hand.
// Source of truth lives in assets/books/<book-id>/book.json and the
// asset filenames themselves. Re-run the script after adding books or readers.

export const BOOKS: Book[] = [
`;

for (const bookId of books) {
  const info = readBookInfo(bookId);
  const pageImages = listFilesMatching(path.join(ASSETS_DIR, bookId, 'pages'), /^page-\d{2}\.png$/);
  const readers = listSubdirs(path.join(ASSETS_DIR, bookId, 'voices'));
  const hasCover = fs.existsSync(path.join(ASSETS_DIR, bookId, 'cover.png'));

  out += `  {\n`;
  out += `    id: '${escapeSingleQuoted(bookId)}',\n`;
  out += `    title: '${escapeSingleQuoted(info.title)}',\n`;
  if (hasCover) {
    out += `    cover: require('../../assets/books/${bookId}/cover.png'),\n`;
  }
  out += `    pages: [\n`;
  for (const p of pageImages) {
    out += `      require('../../assets/books/${bookId}/pages/${p}'),\n`;
  }
  out += `    ],\n`;
  out += `    readers: [\n`;
  for (const readerId of readers) {
    const readerName = (info.readers && info.readers[readerId]) || readerId;
    const audioFiles = listFilesMatching(
      path.join(ASSETS_DIR, bookId, 'voices', readerId),
      /^page-\d{2}\.mp3$/,
    );
    out += `      {\n`;
    out += `        id: '${escapeSingleQuoted(readerId)}',\n`;
    out += `        name: '${escapeSingleQuoted(readerName)}',\n`;
    out += `        pages: [\n`;
    for (const v of audioFiles) {
      out += `          require('../../assets/books/${bookId}/voices/${readerId}/${v}'),\n`;
    }
    out += `        ],\n`;
    out += `      },\n`;
  }
  out += `    ],\n`;
  out += `  },\n`;
}

out += `];\n\n`;

out += `export function validateBooks(books: Book[]): string[] {
  const errors: string[] = [];
  const seenBookIds = new Set<string>();
  for (const book of books) {
    if (seenBookIds.has(book.id)) {
      errors.push(\`Duplicate book id: "\${book.id}".\`);
    }
    seenBookIds.add(book.id);

    if (book.readers.length === 0) {
      errors.push(\`Book "\${book.id}" has no readers; at least one is required.\`);
    }

    if (book.pages.length === 0) {
      errors.push(\`Book "\${book.id}" has no pages; at least one is required.\`);
    }

    const seenReaderIds = new Set<string>();
    for (const reader of book.readers) {
      if (seenReaderIds.has(reader.id)) {
        errors.push(\`Duplicate reader id "\${reader.id}" within book "\${book.id}".\`);
      }
      seenReaderIds.add(reader.id);

      if (reader.pages.length !== book.pages.length) {
        errors.push(
          \`Reader "\${reader.id}" in book "\${book.id}" has \${reader.pages.length} audio pages but the book has \${book.pages.length} image pages.\`,
        );
      }
    }
  }
  return errors;
}
`;

fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
fs.writeFileSync(OUTPUT, out);
console.log(`Wrote ${path.relative(ROOT, OUTPUT)} (${books.length} book${books.length === 1 ? '' : 's'}).`);
